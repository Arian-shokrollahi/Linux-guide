function walk(directory) {
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    if ([".git", "node_modules", "assets", "scripts", ".github"].includes(entry.name)) return [];
    const absolute = path.join(directory, entry.name);
    if (entry.isDirectory()) return walk(absolute);
    if (!entry.isFile() || path.extname(entry.name).toLowerCase() !== ".md") return [];
    if (entry.name.toLowerCase() === "readme.md" && directory === rootDir) return [];
    return [absolute];
  });
}

function cleanTitle(value) {
  return String(value || "")
    .replace(/<[^>]+>/g, "")
    .replace(/!\[([^\]]*)\]\([^)]*\)/g, "$1")
    .replace(/\[([^\]]+)\]\([^)]*\)/g, "$1")
    .replace(/[`*_~]/g, "")
    .replace(/^ا[-–—]\s*/, "")
    .replace(/\s+/g, " ")
    .trim();
}

function fallbackTitle(filePath) {
  return path.basename(filePath, ".md")
    .replace(/^\d+(?:[-_.]\d+)*[-_.]?/, "")
    .replace(/[._-]+/g, " ")
    .trim();
}

function searchText(markdown) {
  return markdown
    .replace(/```[\s\S]*?```/g, " ")
    .replace(/<[^>]+>/g, " ")
    .replace(/!\[[^\]]*\]\([^)]*\)/g, " ")
    .replace(/\[([^\]]+)\]\([^)]*\)/g, "$1")
    .replace(/[`*_>#|~=-]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

function normalize(value) {
  return String(value || "")
    .toLocaleLowerCase("fa")
    .replace(/ي/g, "ی")
    .replace(/ك/g, "ک")
    .replace(/[ـ\u064B-\u065F]/g, "")
    .replace(/[^\p{L}\p{N}+#._-]+/gu, " ")
    .trim();
}

const collator = new Intl.Collator("en", { numeric: true, sensitivity: "base" });
const files = walk(rootDir).sort((a, b) => collator.compare(path.relative(rootDir, a), path.relative(rootDir, b)));

const content = files.map((absolutePath) => {
  const relativePath = path.relative(rootDir, absolutePath).split(path.sep).join("/");
  const markdown = fs.readFileSync(absolutePath, "utf8").replace(/^\uFEFF/, "");
  if (!markdown.trim()) return null;
  const headingMatch = markdown.match(/^#{1,2}\s+(.+)$/m);
  const title = cleanTitle(headingMatch ? headingMatch[1] : fallbackTitle(absolutePath)) || fallbackTitle(absolutePath);
  const categoryKey = relativePath.split("/")[0];
  const category = categoryNames[categoryKey] || cleanTitle(categoryKey.replace(/[._-]+/g, " "));
  const plainText = searchText(markdown);
  const words = plainText ? plainText.split(/\s+/).length : 0;
  const searchable = [title, category, relativePath, plainText].join(" ");

  return {
    path: relativePath,
    title,
    categoryKey,
    category,
    words,
    normalizedSearch: normalize(searchable)
  };
}).filter(Boolean);

fs.mkdirSync(path.dirname(outputFile), { recursive: true });
const serialized = JSON.stringify(content, null, 2).replace(/</g, "\\u003c");
fs.writeFileSync(outputFile, "// Generated by scripts/generate-content-index.mjs\nwindow.LINUX_GUIDE_CONTENT = " + serialized + ";\n", "utf8");
console.log("Generated content index for " + content.length + " Markdown files.");
